import { defineConfig } from 'vitest/config';
import tsconfigPaths from 'vite-tsconfig-paths';

export default defineConfig({
  // Resolves the path aliases declared in tsconfig.json, including the ones
  // added by `nest g library`.
  plugins: [tsconfigPaths()],
  test: {
    globals: true,
    root: './',
    include: ['**/*.spec.ts'],
    coverage: {
      /**
       * include со всем исходным кодом, а не только с тем, что тесты
       * успели импортировать.
       *
       * Без этого отчёт показывает проценты по горстке файлов и выглядит
       * прекрасно ровно до того момента, когда кто-то заметит, что
       * половины приложения в нём просто нет. Непокрытый файл должен
       * портить общую цифру — в этом весь смысл цифры.
       */
      include: ['src/**/*.ts'],
      exclude: [
        // Сами тесты
        'src/**/*.spec.ts',
        // Точка входа и скрипт наполнения базы: это не логика приложения,
        // а способы его запустить. Проверяются тем, что приложение
        // поднимается, — в юнит-тестах поднимать его незачем
        'src/main.ts',
        'src/seed.ts',
        // Объявления таблиц: набор полей с декораторами, без ветвлений.
        // Проверять в них нечего, а в знаменателе они дают заметный вес
        'src/**/entities/*.ts',
        // Описания модулей Nest: тоже декларации, кто с кем собирается.
        // Что сборка верна, показывает поднятие приложения в e2e
        'src/**/*.module.ts',
      ],
      reporter: ['text', 'html'],
      /**
       * Порог, ниже которого прогон считается провалившимся.
       *
       * Стоит здесь, а не в голове у того, кто смотрит отчёт: иначе
       * покрытие сползает по чуть-чуть и однажды обнаруживается сильно
       * ниже, чем все думали.
       */
      thresholds: {
        statements: 70,
        branches: 70,
        functions: 70,
        lines: 70,
      },
    },
  },
});

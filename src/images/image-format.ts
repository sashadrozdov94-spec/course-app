/**
 * Форматы изображений, которые приложение умеет читать и писать.
 *
 * Как и в трансформации текстовых форматов, перечисление — единственное
 * место, где формат объявляется. Но направления здесь собираются не по
 * всем парам: растровые форматы взаимозаменяемы, а SVG — нет. Разница не
 * в реализации, а в природе форматов: из пикселей вектор не собрать, и
 * п. 1.2 ТЗ запрещает это направление навсегда.
 *
 * Поэтому формат относится к одному из двух видов, и от вида зависит,
 * какие направления с ним появятся (см. converters/index.ts).
 */
export enum ImageFormat {
  Png = 'png',
  Jpeg = 'jpeg',
  Svg = 'svg',
}

/**
 * Растровые форматы: сетка пикселей.
 *
 * Читаются и пишутся одинаково, поэтому любой растровый формат
 * конвертируется в любой другой растровый — и служит целью растеризации
 * вектора. Добавится WebP — здесь прибавится одна строка, и вместе с ней
 * появятся png → webp, jpeg → webp, webp → png, webp → jpeg и svg → webp.
 */
export const RASTER_FORMATS: readonly ImageFormat[] = [
  ImageFormat.Png,
  ImageFormat.Jpeg,
];

/**
 * Векторных форматов в отдельном списке нет намеренно.
 *
 * Отрисовка вектора зависит от самого формата — разметку SVG разбирает
 * разборщик SVG, — поэтому новый векторный формат означает новый класс
 * растеризации, а не строку в списке. Такой список создавал бы ложное
 * впечатление, что вектор можно добавить одним значением.
 *
 * Обратное направление, растр → вектор, не появится никогда: п. 1.2 ТЗ
 * исключает векторизацию, и в сборке направлений (converters/index.ts)
 * правила, ведущего в вектор, просто нет.
 */

/**
 * Расширение файла → формат. Подсказка на случай, когда содержимое молчит.
 *
 * У JPEG исторически два расширения, и оба встречаются одинаково часто.
 */
export const FORMAT_BY_EXTENSION: Readonly<Record<string, ImageFormat>> = {
  png: ImageFormat.Png,
  jpg: ImageFormat.Jpeg,
  jpeg: ImageFormat.Jpeg,
  svg: ImageFormat.Svg,
};

/** Что отдавать в Content-Type результата. */
export const MIME_BY_FORMAT: Readonly<Record<ImageFormat, string>> = {
  [ImageFormat.Png]: 'image/png',
  [ImageFormat.Jpeg]: 'image/jpeg',
  // Разметка, а не двоичные данные, поэтому кодировка имеет значение
  [ImageFormat.Svg]: 'image/svg+xml; charset=utf-8',
};

/**
 * Отказ, который можно показать клиенту.
 *
 * Отдельный класс нужен, чтобы сервис отличал «мы посмотрели файл и он не
 * годится» от «где-то внутри что-то сломалось». Тексты у первых написаны
 * для человека и объясняют, что исправить; вторые — это сообщения
 * библиотек на английском, и отдавать их наружу незачем: клиенту они
 * ничего не подскажут, а нам покажут больше устройства приложения, чем
 * стоило бы.
 *
 * Бросают его конвертеры и разбор SVG; сервис превращает в 400.
 */
export class ConversionError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'ConversionError';
  }
}

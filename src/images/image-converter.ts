import type { ImageFormat } from './image-format.js';

/**
 * Необязательные параметры из поля options (п. 1.3.1 ТЗ).
 *
 * Все поля необязательные: чем именно из них распорядиться, решает
 * направление. Для png → jpeg осмысленны quality и background, для
 * svg → png — width, height и background. Какие параметры направление
 * принимает, оно объявляет само (accepts), а лишние сервис отклоняет —
 * молча проигнорированная ширина хуже отказа: клиент получил бы картинку
 * не того размера и не узнал почему.
 */
export interface ConvertOptions {
  /** Качество JPEG, 1–100. */
  quality?: number;
  /** Ширина растра при растеризации вектора, пиксели. */
  width?: number;
  /** Высота растра при растеризации вектора, пиксели. */
  height?: number;
  /** Цвет холста: #rgb, #rgba, #rrggbb, #rrggbbaa или transparent. */
  background?: string;
}

/** Имена параметров — для проверки «это направление такое не умеет». */
export const OPTION_NAMES = [
  'quality',
  'width',
  'height',
  'background',
] as const;

export type OptionName = (typeof OPTION_NAMES)[number];

/**
 * Потолки и умолчания из конфигурации приложения.
 *
 * ТЗ требует, чтобы их задавал администратор, поэтому они приходят
 * параметром, а не лежат константами в коде конвертера: подобрать
 * разумный максимум можно только зная, сколько памяти у машины.
 */
export interface ConversionSettings {
  /** Максимальная ширина растра на выходе. */
  maxWidth: number;
  /** Максимальная высота растра на выходе. */
  maxHeight: number;
  /**
   * Максимум пикселей в изображении — и на входе, и на выходе.
   *
   * Отдельно от ширины и высоты, потому что стороны ограничивают форму, а
   * не объём работы: 8000 × 8000 укладывается в обе стороны, но это 64
   * миллиона пикселей и четверть гигабайта памяти под несжатый растр.
   */
  maxPixels: number;
  /** Размер стороны, когда у SVG нет собственного (п. 1.3.1 ТЗ). */
  defaultSize: number;
  /** Сколько отведено на саму конвертацию. */
  timeoutMs: number;
  /** Качество JPEG, если клиент не указал своего. */
  defaultQuality: number;
  /** Цвет холста, если клиент не указал своего. По ТЗ — #ffffff. */
  defaultBackground: string;
}

/**
 * Одно направление конвертации изображений.
 *
 * Абстрактный класс, а не интерфейс, по той же причине, что и в
 * трансформации текстовых форматов: интерфейс в TypeScript исчезает при
 * сборке, а класс остаётся — направления лежат в массиве и создаются на
 * лету. Заодно здесь живёт общее описание direction.
 *
 * Реализаций две, и делятся они не по парам форматов, а по природе работы:
 * перекодирование растра в растр и растеризация вектора. Отсюда и число
 * классов: четыре направления из ТЗ — это два класса, а не четыре.
 */
export abstract class ImageConverter {
  /** Из какого формата читает. */
  abstract readonly source: ImageFormat;

  /** В какой формат пишет. */
  abstract readonly target: ImageFormat;

  /**
   * Какие поля options имеют смысл для этого направления.
   *
   * Объявляет само направление, потому что только оно знает, что умеет:
   * ширина при перекодировании растра ничего не значит, а качество для
   * PNG не значит ничего нигде — у него сжатие без потерь.
   */
  abstract readonly accepts: readonly OptionName[];

  /**
   * Собственно преобразование.
   *
   * Асинхронное, потому что таким его делает работа с изображениями:
   * декодирование и кодирование идут в пуле потоков libuv, а не в потоке
   * событий. Ошибку нужно бросать обычным Error с понятным текстом —
   * сервис переведёт её в 400.
   */
  abstract convert(
    input: Buffer,
    options: ConvertOptions,
    settings: ConversionSettings,
  ): Promise<Buffer>;

  /** Человекочитаемое направление, например «svg → png». */
  get direction(): string {
    return `${this.source} → ${this.target}`;
  }
}

import type { Readable } from 'node:stream';

/**
 * Хранилище файлов.
 *
 * Абстрактный класс, а не интерфейс: интерфейс в TypeScript исчезает при
 * сборке, а Nest нужен живой объект, чтобы выдать зависимость по классу —
 * так реализацию можно подменить одной строкой в модуле, а всё остальное
 * приложение продолжит просить FileStorage.
 *
 * Сейчас реализация одна — на диске (disk-file-storage.ts). Абстракция
 * заведена не «на будущее», а потому, что без неё бизнес-логика знала бы
 * про пути, каталоги и unlink: заменить диск на что угодно другое значило
 * бы править конвертацию и уборку истории, которые к хранению отношения
 * не имеют.
 *
 * Ключ (key) непрозрачен для вызывающего кода: его выдаёт само хранилище
 * при записи, и что внутри — путь, имя объекта или строка из базы, — знает
 * только оно. Снаружи ключ только хранят в строке истории и возвращают
 * обратно.
 */
export abstract class FileStorage {
  /**
   * Положить файл и вернуть его ключ.
   *
   * extension — подсказка для человека, который однажды заглянет в
   * хранилище глазами: по ней у файла будет узнаваемое расширение.
   * На поиск и выдачу она не влияет.
   *
   * Ошибку бросаем как есть: не сохранить файл, о котором попросили, —
   * это отказ, а не мелочь, и вызывающий код должен о нём узнать.
   */
  abstract put(body: Buffer, extension: string): Promise<string>;

  /**
   * Открыть файл на чтение.
   *
   * Поток, а не буфер: ТЗ требует потоковой передачи, и держать в памяти
   * файл целиком ради того, чтобы тут же отдать его в сеть, незачем.
   *
   * null означает «такого файла нет» — обычное дело при рассинхронизации
   * записи и хранилища, а не сбой.
   */
  abstract open(key: string): Promise<Readable | null>;

  /**
   * Удалить файл. Возвращает true, если файл был и его убрали.
   *
   * Отсутствие файла — не ошибка: уборка должна быть повторяемой, и
   * второй заход по тому же ключу обязан пройти спокойно.
   */
  abstract remove(key: string): Promise<boolean>;
}

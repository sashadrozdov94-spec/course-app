import {
  Column,
  CreateDateColumn,
  Entity,
  Index,
  PrimaryGeneratedColumn,
} from 'typeorm';
import { TransformationStatus, TransformationType } from '../transformation.js';

/**
 * Таблица transformations — единая история всех трансформаций.
 *
 * Одна таблица на файлы и картинки, как требует п. 1.1 ТЗ. Раньше история
 * файлов лежала в file_conversions, а история картинок только в журнале
 * приложения; собрать из этого одну страницу с курсором было бы нечем:
 * курсор — это «продолжи с этого места» в одном упорядоченном наборе, а
 * не в двух независимых.
 *
 * Хранит то, что требует п. 1.5: кто, что во что, размер входа, результат
 * и длительность. Содержимого файлов здесь нет и быть не должно — это
 * запрещено прямо и разумно: в конвертируемых данных бывает что угодно.
 *
 * Внешнего ключа на users намеренно нет: история должна пережить удаление
 * аккаунта, как и записи журналов auth и rbac. Срок её жизни определяет
 * не удаление пользователя, а срок хранения из настроек
 * (history-retention.service.ts).
 */
@Entity({ name: 'transformations' })
// Главный порядок чтения: история одного человека, новые сверху. Под него
// же ложится курсор — пара (createdAt, id) из этого индекса.
@Index(['userId', 'createdAt'])
// Фильтры из п. 1.3.1 поверх того же порядка. Отдельные индексы, а не
// один общий: фильтры независимы, и в запросе бывает любой из них или ни
// одного. П. 1.6 ТЗ требует индексы по userId, createdAt, type и status —
// это они.
@Index(['userId', 'type', 'createdAt'])
@Index(['userId', 'status', 'createdAt'])
// Для фоновой уборки: она ищет просроченное по всем пользователям сразу,
// и индексы выше, начинающиеся с userId, ей не годятся
@Index(['expiresAt'])
export class Transformation {
  @PrimaryGeneratedColumn('uuid')
  id: string;

  /** Кто выполнял. Привязка к пользователю, которую требует ТЗ. */
  @Column({ type: 'uuid' })
  userId: string;

  @Column({ type: 'enum', enum: TransformationType })
  type: TransformationType;

  /**
   * Имя исходного файла. Само имя — не содержимое, хранить его можно.
   *
   * В ответ API оно не попадает: в списке из п. 1.3.1 его нет, а через
   * административное окно имена чужих файлов видеть незачем (п. 1.4 ТЗ
   * просит не раскрывать лишнего о других). Здесь оно лежит для разбора
   * происшествий.
   */
  @Column({ type: 'varchar', length: 255, nullable: true })
  sourceName: string | null;

  /**
   * Форматы — строки, а не перечисление базы.
   *
   * В эту колонку пишут два модуля со своими наборами форматов, и общего
   * перечисления у них нет: csv и png — значения из разных словарей.
   * Свести их в один enum на стороне базы значило бы править тип колонки
   * при каждом новом формате, то есть менять схему ради записи, которая
   * этого не требует. Допустимые значения проверяются там, где они
   * известны, — на входе фильтра (dto/list-history.dto.ts).
   */
  @Column({ type: 'varchar', length: 16 })
  sourceFormat: string;

  @Column({ type: 'varchar', length: 16 })
  targetFormat: string;

  @Column({ type: 'enum', enum: TransformationStatus })
  status: TransformationStatus;

  /** Код ответа: 200, 400, 413, 415, 504. */
  @Column({ type: 'int' })
  statusCode: number;

  /** Размер исходного файла в байтах. */
  @Column({ type: 'int' })
  fileSize: number;

  /** null, если трансформация не дошла до результата. */
  @Column({ type: 'int', nullable: true })
  resultSize: number | null;

  /** Короткая причина отказа. Без содержимого файла. */
  @Column({ type: 'varchar', length: 255, nullable: true })
  error: string | null;

  /** Сколько заняла сама трансформация, миллисекунды. */
  @Column({ type: 'int' })
  durationMs: number;

  /**
   * Ключ сохранённого результата в хранилище. null — не сохраняли.
   *
   * Непрозрачен: что внутри — путь, имя объекта или что-то ещё, — знает
   * только само хранилище (см. storage/file-storage.ts). Наружу, клиенту,
   * ключ не отдаётся никогда: скачивание идёт по номеру записи истории, а
   * право на неё проверяется каждый раз. Прямая ссылка на файл, даже
   * неугадываемая, — это доступ без проверки, и отозвать его нечем.
   */
  @Column({ type: 'varchar', length: 128, nullable: true })
  fileId: string | null;

  /**
   * Имя, под которым файл отдаётся при скачивании.
   *
   * Собрано нами (converted.json), а не взято из загруженного файла:
   * имя из формы — это строка от клиента, а она попадает в заголовок
   * Content-Disposition. Хранить готовое имя надёжнее, чем собирать его
   * при выдаче: так скачанное из истории совпадает с тем, что клиент
   * получил в ответ на саму конвертацию.
   */
  @Column({ type: 'varchar', length: 255, nullable: true })
  resultName: string | null;

  /** Content-Type сохранённого результата. */
  @Column({ type: 'varchar', length: 128, nullable: true })
  resultMime: string | null;

  /**
   * Когда файл перестаёт быть доступен.
   *
   * Считается от срока хранения истории: ТЗ требует, чтобы файл жил
   * ровно столько же, сколько запись. Хранится отдельной колонкой, а не
   * вычисляется из createdAt при каждом запросе, по двум причинам: срок в
   * настройках могут поменять, и тогда уже сохранённые файлы не должны
   * менять свою судьбу задним числом; и по этой колонке уборке удобно
   * искать просроченное.
   *
   * null у записей без файла и у настроенных «хранить вечно».
   */
  @Column({ type: 'timestamptz', nullable: true })
  expiresAt: Date | null;

  @CreateDateColumn({ type: 'timestamptz' })
  createdAt: Date;
}

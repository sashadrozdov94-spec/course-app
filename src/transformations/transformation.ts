/**
 * Вид трансформации: что именно преобразовывали.
 *
 * Хранилище истории одно на оба модуля — этого прямо требует п. 1.1 ТЗ
 * («все трансформации логируются в единое хранилище»), — но в списке их
 * надо различать, иначе фильтр «покажи только картинки» не собрать.
 *
 * Различаются они именно видом, а не форматом: набор форматов у каждого
 * свой и со временем пополнится, а видов останется два — пиксели и текст
 * требуют разной обработки, и это свойство самой задачи.
 */
export enum TransformationType {
  File = 'file',
  Image = 'image',
}

/** Чем закончилась трансформация. */
export enum TransformationStatus {
  Success = 'success',
  Error = 'error',
}

/**
 * Что записано в графе формата, когда формат определить не удалось.
 *
 * Такие попытки тоже попадают в историю: по ним видно, что кто-то
 * систематически шлёт не то, — а именно это и стоит замечать. Отдельное
 * значение, а не пустая колонка, потому что в контракте из п. 1.3.1 ТЗ
 * поле sourceFormat — строка, и клиенту незачем разбирать ещё и null.
 * Заодно по нему можно отфильтровать.
 */
export const UNKNOWN_FORMAT = 'unknown';

/**
 * Разрешение RBAC, которым закрыта чужая история, и его действия.
 *
 * ТЗ называет право `transformations.history.admin`; в этом проекте права
 * записываются как «ресурс@действие» (см. RequirePermission), поэтому то
 * же самое здесь выглядит как `transformations@history_admin`. Имя и
 * действия обязаны совпадать со строками в таблице permissions: связь
 * между кодом и конфигурацией держится на них.
 *
 * Своей истории право не требуется: её видно и так, и отдельного действия
 * на «посмотреть себя» в ТЗ нет.
 */
export const TRANSFORMATIONS_PERMISSION = 'transformations';

export const TRANSFORMATIONS_ACTIONS = {
  /** Просмотр истории любого пользователя */
  HistoryAdmin: 'history_admin',
} as const;

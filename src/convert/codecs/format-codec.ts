import type { FileFormat } from '../format.js';

/**
 * Чтение и запись одного формата.
 *
 * Почему кодек, а не класс на каждое направление. Направлений из ТЗ
 * двенадцать, а форматов четыре. Двенадцать классов вида «csv → yaml»
 * означали бы, что разбор CSV написан трижды, а сборка YAML — трижды, и
 * исправление в одном месте забывалось бы в двух других. Кодек описывает
 * формат один раз, а направления собираются как все пары
 * (кодек-читатель, кодек-писатель) — см. converters/index.ts.
 *
 * Счёт такой: четыре кодека дают двенадцать направлений; пятый формат —
 * это один новый класс и восемь новых направлений даром.
 *
 * Посередине — обычное значение JavaScript: объект, массив, строка,
 * число, логическое или null. Это и есть «внутреннее представление» из
 * п. 1.3.1 ТЗ. Оно совпадает с моделью данных JSON, потому что она самая
 * бедная из четырёх: всё, что через неё проходит, ляжет и в XML, и в
 * YAML, и в CSV.
 *
 * Важно: кодеки не зависят ни от Nest, ни от чего-либо из контейнера.
 * Конвертация выполняется в отдельном потоке, где контейнера нет, поэтому
 * parse и serialize — чистые функции.
 */
export abstract class FormatCodec {
  /** Какой формат читает и пишет. */
  abstract readonly format: FileFormat;

  /**
   * Текст формата → внутреннее представление.
   *
   * На входе — уже прочитанный UTF-8 без BOM. Синтаксическую ошибку нужно
   * бросать обычным Error с понятным текстом: сервис переведёт её в 400.
   */
  abstract parse(input: string): unknown;

  /**
   * Внутреннее представление → текст формата.
   *
   * Если данные не ложатся в формат (например, в CSV нечего записать),
   * тоже бросаем Error: лучше отказ с объяснением, чем файл-обманка.
   */
  abstract serialize(value: unknown): string;
}

import { FileFormat } from './format.js';

/**
 * Сколько первых строк смотрим, решая, таблица ли перед нами.
 *
 * Пяти хватает: у настоящего CSV число полей совпадает уже на них, а
 * читать ради догадки весь десятимегабайтный файл незачем — настоящий
 * разбор всё равно впереди.
 */
const CSV_PROBE_LINES = 5;

/**
 * Начало документа YAML: --- (начало документа) или %YAML (директива).
 * Однозначный признак: ни в одном из трёх других форматов такого нет.
 */
const YAML_DOCUMENT_START = /^(?:---(?:\s|$)|%YAML\s)/;

/**
 * Строка YAML: «ключ: значение» или «- элемент».
 *
 * Ключ не должен содержать запятую — иначе заголовок CSV вида
 * «id,label:ru» мы бы приняли за YAML. После дефиса обязателен пробел: без
 * него это не элемент списка, а отрицательное число вроде -1,5.
 */
const YAML_LINE = /^(?:-\s|[^,:\n]+:(?:\s|$))/;

/** С чего может начинаться скалярный документ JSON (RFC 8259). */
const JSON_SCALAR_START = /^(?:"|-?\d|true\b|false\b|null\b)/;

/**
 * Определение исходного формата.
 *
 * ТЗ разрешает опираться на содержимое или расширение. Смотрим сначала в
 * содержимое и только потом на расширение: расширение задаёт клиент, и оно
 * запросто врёт — файл mydata.json может оказаться выгрузкой XML. Ошибиться
 * здесь дороже, чем кажется: разбор пошёл бы не тем парсером и вернул
 * невнятную ошибку синтаксиса вместо честного «формат не тот».
 *
 * Порядок проверок — от однозначных признаков к догадкам:
 *
 *   1. «<» бывает в начале только у XML;
 *   2. --- и %YAML бывают только у YAML;
 *   3. «{» и «[» — это JSON; но поточный YAML умеет то же самое, поэтому
 *      здесь расширение получает право голоса;
 *   4. «ключ: значение» и «- элемент» — YAML;
 *   5. несколько строк с одинаковым числом полей через запятую — CSV;
 *   6. скаляр вида "строка", 42, true — JSON;
 *   7. ничего не подошло — верим расширению.
 *
 * Полностью развести CSV и YAML по содержимому нельзя: файл из одной
 * колонки без запятых — это и корректный CSV, и корректный YAML. Такие
 * случаи и разрешает расширение на последнем шаге.
 *
 * Документ здесь не разбираем, только смотрим на признаки: настоящая
 * проверка синтаксиса всё равно впереди, в кодеке, и дублировать её здесь
 * незачем — тем более что разбор файла на несколько мегабайт занял бы
 * основной поток, ради чего и заведён рабочий.
 */
export function detectFormat(
  text: string,
  extensionHint?: FileFormat,
): FileFormat | null {
  const head = text.trimStart();

  if (head.length === 0) {
    // Пустой файл: содержимое не говорит ничего, поэтому единственная
    // подсказка — расширение. Про пустоту скажет вызывающий код.
    return extensionHint ?? null;
  }

  // XML начинается с угловой скобки: <?xml, <!DOCTYPE, <!-- или тег
  if (head.startsWith('<')) {
    return FileFormat.Xml;
  }

  if (YAML_DOCUMENT_START.test(head)) {
    return FileFormat.Yaml;
  }

  // Объект и массив: разметка общая у JSON и поточного YAML. Считаем это
  // JSON — так чаще всего и есть, — но уступаем прямому указанию в имени.
  if (head.startsWith('{') || head.startsWith('[')) {
    return extensionHint === FileFormat.Yaml
      ? FileFormat.Yaml
      : FileFormat.Json;
  }

  const firstLine = head.slice(0, head.search(/\r?\n|$/));

  if (YAML_LINE.test(firstLine)) {
    return FileFormat.Yaml;
  }

  if (looksLikeTable(head)) {
    return FileFormat.Csv;
  }

  // Строки, числа и литералы — тоже документы JSON: "text" валиден сам по
  // себе. Проверяем после таблицы: "имя","адрес" — это заголовок CSV, а не
  // строка JSON.
  if (JSON_SCALAR_START.test(head)) {
    return FileFormat.Json;
  }

  return extensionHint ?? null;
}

/**
 * Похоже ли на таблицу: несколько полей через запятую и одинаковое их
 * число в каждой строке.
 *
 * Совпадение числа полей важнее самой запятой: запятая встречается в любом
 * тексте, а вот ровные строки — примета именно таблицы.
 */
function looksLikeTable(text: string): boolean {
  const lines = text
    .split(/\r?\n/)
    .filter((line) => line.trim().length > 0)
    .slice(0, CSV_PROBE_LINES);

  if (lines.length === 0) {
    return false;
  }

  const expected = countFields(lines[0]!);

  return expected > 1 && lines.every((line) => countFields(line) === expected);
}

/**
 * Сколько полей в строке.
 *
 * Запятые внутри кавычек не считаем: «Иванов, Иван» — это одно поле, и
 * иначе строка выглядела бы шире остальных, а файл — не таблицей.
 */
function countFields(line: string): number {
  let fields = 1;
  let quoted = false;

  for (const char of line) {
    if (char === '"') {
      quoted = !quoted;
      continue;
    }

    if (char === ',' && !quoted) {
      fields += 1;
    }
  }

  return fields;
}

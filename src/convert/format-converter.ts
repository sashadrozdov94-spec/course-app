import type { FileFormat } from './format.js';

/**
 * Одно направление трансформации: из одного формата в другой.
 *
 * Абстрактный класс, а не интерфейс: интерфейс в TypeScript исчезает при
 * сборке, а класс остаётся — конвертеры лежат в массиве и создаются на
 * лету, в том числе внутри рабочего потока. Заодно здесь живёт общее для
 * всех направлений описание (direction), и повторять его негде.
 *
 * Единственная реализация — CodecConverter: он склеивает два кодека,
 * читателя и писателя. Поэтому новый формат добавляется одним кодеком
 * (codecs/), а не набором классов на каждое направление; сам этот класс
 * трогать не нужно.
 *
 * Важно: реализации не должны зависеть ни от Nest, ни от чего-либо, что
 * живёт в контейнере. Конвертация выполняется в отдельном потоке, где
 * контейнера нет, поэтому convert — чистая функция от строки к строке.
 */
export abstract class FormatConverter {
  /** Из какого формата читает. */
  abstract readonly source: FileFormat;

  /** В какой формат пишет. */
  abstract readonly target: FileFormat;

  /**
   * Собственно преобразование.
   *
   * На входе — уже прочитанный текст в UTF-8 без BOM. На выходе — текст в
   * целевом формате. Ошибку разбора нужно бросать обычным Error: сервис
   * переведёт её в 400 с понятным сообщением.
   */
  abstract convert(input: string): string;

  /** Человекочитаемое направление, например «xml → json». */
  get direction(): string {
    return `${this.source} → ${this.target}`;
  }
}

/**
 * Ограничения на структуру данных (п. 1.6 ТЗ: «ограничение глубины/размера
 * структуры; защита от ресурсных атак»).
 *
 * Лимита на размер файла недостаточно. Полтора килобайта вида
 * `[[[[[[...]]]]]]` — это тысяча уровней вложенности: рекурсивный обход
 * такой структуры съедает стек, и процесс падает целиком, а не отдаёт 400.
 * Поэтому проверяем структуру сразу после разбора, до записи результата.
 */

/** Насколько глубоко разрешено вкладывать. */
const MAX_DEPTH = 64;

/**
 * Сколько всего значений разрешено. Защита от «широких», а не глубоких
 * данных.
 *
 * Планка соотнесена с лимитами на размер файла: в мегабайте JSON помещается
 * порядка сотен тысяч значений, поэтому миллион отсекает только то, что
 * раздулось при разборе, и не мешает честной выгрузке таблицы на десятки
 * тысяч строк.
 */
const MAX_NODES = 1_000_000;

/**
 * Проверяет глубину и число значений.
 *
 * Обход итеративный, со своим стеком: рекурсивная проверка сама упала бы
 * на той самой структуре, от которой защищает. В стек кладём только
 * контейнеры — простые значения считаем на месте, иначе стек повторил бы
 * размер самих данных.
 */
export function assertStructure(value: unknown): void {
  const stack: { node: object; depth: number }[] = [];
  let nodes = 1;

  const visit = (node: unknown, depth: number): void => {
    nodes += 1;

    if (nodes > MAX_NODES) {
      throw new Error(`Слишком много элементов: больше ${MAX_NODES}`);
    }

    if (node === null || typeof node !== 'object') {
      return;
    }

    if (depth > MAX_DEPTH) {
      throw new Error(
        `Слишком глубокая структура: больше ${MAX_DEPTH} уровней вложенности`,
      );
    }

    stack.push({ node, depth });
  };

  if (value !== null && typeof value === 'object') {
    stack.push({ node: value, depth: 1 });
  }

  while (stack.length > 0) {
    const { node, depth } = stack.pop()!;

    for (const child of Object.values(node)) {
      visit(child, depth + 1);
    }
  }
}
